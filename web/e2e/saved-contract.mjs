import { runUiTest } from './ui-test-utils.mjs'

await runUiTest(4253, async ({ browser, url, check }) => {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []; page.on('pageerror', error => errors.push(String(error)))
  await page.goto(url)
  await page.waitForSelector('.discovery-item')
  const cards = page.locator('.discovery-card')
  const originals = await page.locator('.discovery-name').allTextContents()
  const rect = await page.locator('.discovery-grid').boundingBox()
  const trigger = cards.first().getByRole('button', { name: /Details for/ })
  await trigger.click()
  await page.getByRole('dialog').waitFor()
  check(Math.abs((await page.locator('.discovery-grid').boundingBox()).width - rect.width) < 1, 'Details does not resize the underlying grid')
  check(await page.getByRole('dialog').innerText().then(text => text.includes(originals[0])), 'Details shows the selected name')
  await page.keyboard.press('Escape')
  check(await trigger.evaluate(node => node === document.activeElement), 'Escape returns focus to the exact Details trigger')
  for (let i = 0; i < 5; i++) await cards.nth(i).getByRole('button', { name: `Save ${originals[i]}`, exact: true }).click()
  await page.getByRole('button', { name: /^Saved/ }).first().click()
  check(await page.locator('.saved-item').count() === 5, 'Saved displays explicit saves in their original order')
  const preferences = await page.evaluate(() => localStorage.getItem('neologism:favorites'))
  await page.getByRole('searchbox').fill(originals[0].toUpperCase())
  check(await page.locator('.saved-item').count() === 1, 'search is case insensitive')
  await page.getByRole('searchbox').fill('zzzz-no-such-saved-name')
  check(await page.getByRole('button', { name: 'Clear search' }).isVisible(), 'empty search offers a recovery action')
  await page.getByRole('button', { name: 'Clear search' }).click()
  check(await page.getByRole('button', { name: 'Compare', exact: true }).isDisabled(), 'comparison needs at least two names')
  for (let i = 0; i < 4; i++) await page.getByRole('checkbox').nth(i).check()
  check(await page.getByRole('checkbox').nth(4).isDisabled(), 'comparison prevents a fifth selection')
  await page.getByRole('button', { name: 'Compare (4)', exact: true }).click()
  check(await page.getByRole('table').locator('thead th').count() === 5, 'four names appear side by side with row labels')
  check(await page.getByRole('table').innerText().then(text => text.includes('Live checks') && !text.includes('Winner')), 'comparison reports check state without an automatic winner')
  await page.keyboard.press('Escape')
  check(await page.getByRole('button', { name: 'Compare (4)' }).evaluate(node => node === document.activeElement), 'comparison restores keyboard focus')
  check(await page.evaluate(() => localStorage.getItem('neologism:favorites')) === preferences, 'search and comparison do not change preferences')
  await page.getByRole('button', { name: `Remove ${originals[0]} from Saved`, exact: true }).click()
  check(await page.locator('.saved-item').count() === 4, 'remove immediately updates Saved')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await cards.nth(5).getByRole('button', { name: `Save ${originals[5]}`, exact: true }).click()
  await page.getByRole('button', { name: /^Saved/ }).first().click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  const restored = await page.locator('.saved-item .discovery-name').allTextContents()
  check(restored.length === 6 && restored[0] === originals[0] && restored[5] === originals[5], 'Undo restores the removed position and preserves later saves')
  await page.getByRole('button', { name: `Remove ${originals[0]} from Saved`, exact: true }).click()
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  await cards.first().getByRole('button', { name: `Save ${originals[0]}`, exact: true }).click()
  await page.getByRole('button', { name: /^Saved/ }).first().click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  check((await page.locator('.saved-item .discovery-name').allTextContents()).at(-1) === originals[0], 'Undo does not revert a later choice for the same name')
  const pure = await page.evaluate(async () => {
    const { captureSavedRemoval, restoreSavedRemoval } = await import('/src/lib/saved-undo.ts')
    const a = { name: 'Anchor', style: 'big_tech', syllables: 2, score_pronounce: 90, score_novelty: 70, score_memorability: 80, connotations: [] }
    const b = { ...a, name: 'Other' }
    const scoped = { ...a, tasteContext: { id: 'scope-2', roots: [] } }
    const shared = { name: 'anchor', style: 'big_tech', syllables: 0, score_pronounce: 0, score_novelty: 0, score_memorability: 0, connotations: [] }
    const receipt = captureSavedRemoval(a, [a, b, scoped], [shared], [])
    const result = restoreSavedRemoval(receipt, [b], [], [])
    const sharedOnly = restoreSavedRemoval(captureSavedRemoval(shared, [], [shared], []), [], [], [])
    return { sources: result.favorites.length === 3 && result.imported.length === 1, importedNeutral: sharedOnly.favorites.length === 0 && sharedOnly.imported.length === 1, passKept: restoreSavedRemoval(receipt, [b], [], [a]) === null }
  })
  check(pure.sources && pure.importedNeutral && pure.passKept, 'Undo preserves scoped and shared sources and refuses to overwrite a later Pass')
  await page.reload()
  check(await page.locator('.saved-item').count() === 6, 'all saved generator families survive reload')
  check(errors.length === 0, 'Saved and Details have no uncaught browser errors')
})
