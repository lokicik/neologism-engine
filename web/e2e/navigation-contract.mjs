import { runUiTest } from './ui-test-utils.mjs'
await runUiTest(4256, async ({ browser, url, check }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const page = await context.newPage(); const errors = []
  page.on('pageerror', error => errors.push(String(error)))
  await page.goto(url)
  await page.waitForSelector('.discovery-card')
  const discovery = await page.locator('.discovery-name').allTextContents()
  await page.getByRole('button', { name: 'Skip to main content' }).focus()
  await page.keyboard.press('Enter')
  check(await page.locator('#main-content').evaluate(node => node === document.activeElement), 'skip link reaches main content by keyboard')
  await page.locator('.tools-menu summary').click()
  await page.getByRole('button', { name: /^Lab/ }).click()
  check(new URL(page.url()).searchParams.get('view') === 'lab', 'Lab has its own query route')
  await page.getByRole('combobox', { name: 'Method', exact: true }).waitFor()
  check(await page.getByRole('combobox', { name: 'Method', exact: true }).locator('option').count() === 16, 'all existing methods stay in one Lab selector')
  await page.getByRole('combobox', { name: 'Method', exact: true }).selectOption('product_names')
  await page.locator('.lab-page .command-input').fill('database migrations')
  await page.locator('.lab-page .command-go').click()
  await page.waitForFunction(() => !document.querySelector('.lab-page .command-go').disabled)
  check(await page.locator('.finalist').count() > 0, 'Product names Lab still generates finalists')
  await page.getByRole('button', { name: 'Create', exact: true }).click()
  check(JSON.stringify(await page.locator('.discovery-name').allTextContents()) === JSON.stringify(discovery), 'Lab generation cannot replace Create results')
  await page.locator('.tools-menu summary').click()
  await page.getByRole('button', { name: /^AI Studio/ }).click()
  check(new URL(page.url()).searchParams.get('view') === 'studio', 'AI Studio remains a separate tool')
  await page.getByRole('button', { name: /^Saved/ }).first().click()
  await page.goBack()
  check(new URL(page.url()).searchParams.get('view') === 'studio' && (await page.title()).startsWith('AI Studio'), 'browser Back restores the routed view and title')
  await page.locator('.tools-menu summary').click()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByRole('dialog').waitFor()
  check(new URL(page.url()).searchParams.get('view') === 'studio', 'Settings does not replace the underlying route')
  await page.keyboard.press('Escape')
  check(await page.getByRole('dialog').count() === 0, 'Settings closes with Escape')
  await page.locator('.tools-menu summary').click()
  await page.getByRole('button', { name: 'About', exact: true }).click()
  check(new URL(page.url()).searchParams.get('view') === 'about', 'About stays under Tools')
  const payload = Buffer.from(JSON.stringify([{ n: 'SharedAnchor', s: 'big_tech' }, { n: 'SharedBeacon', s: 'fantasy' }])).toString('base64')
  await page.goto(url + '/#names=' + payload)
  await page.getByRole('heading', { name: 'Saved names', exact: true }).waitFor()
  const state = await page.evaluate(() => ({ query: location.search, imports: JSON.parse(localStorage.getItem('neologism:imported-saved') ?? '[]'), likes: JSON.parse(localStorage.getItem('neologism:favorites') ?? '[]') }))
  check(state.query === '?view=saved' && state.imports.length === 2 && state.likes.length === 0, 'existing share links open Saved and stay separate from preferences')
  await page.getByRole('button', { name: 'Remove SharedAnchor from Saved', exact: true }).click()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  check(await page.evaluate(() => JSON.parse(localStorage.getItem('neologism:imported-saved')).length === 2 && JSON.parse(localStorage.getItem('neologism:favorites') ?? '[]').length === 0), 'Undo of a share-only name never creates a like')
  await page.getByRole('button', { name: 'Details for SharedAnchor' }).click()
  check(!(await page.getByRole('dialog').innerText()).includes('Structural estimates'), 'shared names have no fabricated scores')
  await page.keyboard.press('Escape')
  // Live observations are retained for comparison, with source and time.
  await page.evaluate(async () => {
    const { rememberNameChecks } = await import('/src/lib/session-checks.ts')
    rememberNameChecks('SharedAnchor', [{ tld: '.com', host: 'sharedanchor.com', method: 'rdap', provider: 'Fixture registry', status: 'record_found', checkedAt: 1700000000000, cached: false, source: 'network', cooldownUntil: null }])
  })
  await page.getByRole('checkbox').nth(0).check(); await page.getByRole('checkbox').nth(1).check()
  await page.getByRole('button', { name: 'Compare (2)' }).click()
  check((await page.getByRole('table').innerText()).includes('Fixture registry') && (await page.getByRole('table').innerText()).includes('Registration record found'), 'comparison carries existing check observations and source rather than guessing availability')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Remove SharedAnchor from Saved' }).click()
  await page.evaluate(() => { const original = Storage.prototype.setItem; window.restoreWrites = () => { Storage.prototype.setItem = original }; Storage.prototype.setItem = function(key,value) { if (key === 'neologism:imported-saved') throw new Error('fixture quota'); return original.call(this,key,value) } })
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  check(await page.locator('.saved-item').count() === 1 && (await page.locator('.saved-action-status').textContent()).includes('Could not undo'), 'failed Undo retains durable data and offers retry')
  await page.evaluate(() => restoreWrites())
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  check(await page.locator('.saved-item').count() === 2, 'Undo retries successfully after a storage failure')
  check(errors.length === 0, 'navigation and shared-name flows produce no uncaught errors')
})
